export const PLACEHOLDER_NOTE = 'Clickco dev passthrough: RAW export pending - not a real export';

/**
 * The 1×1 JPEG with a COM (FF FE) segment right after SOI carrying `note`, so anyone opening the
 * file sees what it is. Never decodes the RAW.
 */
export function placeholderJpeg(note: string = PLACEHOLDER_NOTE): Buffer {
  const base = Buffer.from(ONE_PIXEL_JPEG_BASE64, 'base64');
  const text = Buffer.from(note, 'latin1');
  const length = Buffer.alloc(2);
  length.writeUInt16BE(text.length + 2);
  return Buffer.concat([
    base.subarray(0, 2),
    Buffer.from([0xff, 0xfe]),
    length,
    text,
    base.subarray(2),
  ]);
}
